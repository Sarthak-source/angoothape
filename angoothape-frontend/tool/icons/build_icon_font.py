"""Builds the ApIcons font from the icon set in the HTML prototype.

Usage (needs `pip install picosvg fonttools`):
    python3 tool/icons/build_icon_font.py

Reads the `IP` and `FPRINT` icon tables from
`assets/angoothape-prototype-v2 (1).html`, converts the 2px rounded strokes
into filled outlines, and writes:
    assets/icons/svg/<name>.svg     source icons
    assets/fonts/ApIcons.ttf        icon font
    lib/core/theme/ap_icons.dart    IconData constants
"""

import re
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
from picosvg.svg import SVG

ROOT = Path(__file__).resolve().parents[2]
HTML = ROOT / "assets" / "angoothape-prototype-v2 (1).html"
SVG_DIR = ROOT / "assets" / "icons" / "svg"
FONT = ROOT / "assets" / "fonts" / "ApIcons.ttf"
DART = ROOT / "lib" / "core" / "theme" / "ap_icons.dart"

UPM = 1024
FIRST_CODEPOINT = 0xE000
FAMILY = "ApIcons"

# Prototype keys that clash with Dart keywords or read poorly as identifiers.
RENAME = {"x": "close", "finger": "fingerprintSimple"}


def read_icons() -> dict[str, str]:
    html = HTML.read_text(encoding="utf-8")
    table = re.search(r"const IP = \{(.*?)\n\};", html, re.S).group(1)
    icons = dict(re.findall(r"(\w+)\s*:\s*'([^']*)'", table))
    icons["fingerprint"] = re.search(r"const FPRINT = '([^']*)'", html).group(1)
    return {RENAME.get(k, k): v for k, v in icons.items()}


def to_svg(body: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        'fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" '
        f'stroke-linejoin="round">{body}</svg>'
    )


def glyph_for(svg_text: str):
    pico = SVG.fromstring(svg_text).topicosvg()
    pen = TTGlyphPen(None)
    scale = UPM / 24
    # SVG is y-down; fonts are y-up with the baseline at the bottom of the box.
    flip = TransformPen(Cu2QuPen(pen, max_err=1.0, reverse_direction=True),
                        (scale, 0, 0, -scale, 0, UPM))
    for shape in pico.shapes():
        parse_path(shape.as_path().d, flip)
    return pen.glyph()


def main() -> None:
    icons = read_icons()
    SVG_DIR.mkdir(parents=True, exist_ok=True)
    FONT.parent.mkdir(parents=True, exist_ok=True)

    names = sorted(icons)
    glyph_order = [".notdef"] + names
    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    cmap = {}
    for i, name in enumerate(names):
        svg_text = to_svg(icons[name])
        (SVG_DIR / f"{name}.svg").write_text(svg_text + "\n", encoding="utf-8")
        glyphs[name] = glyph_for(svg_text)
        cmap[FIRST_CODEPOINT + i] = name

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (UPM, 0) for g in glyph_order})
    fb.setupHorizontalHeader(ascent=UPM, descent=0)
    fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, usWinAscent=UPM,
                usWinDescent=0)
    fb.setupPost()
    fb.save(str(FONT))

    lines = [
        "// Generated by tool/icons/build_icon_font.py from the HTML prototype.",
        "// Do not edit by hand.",
        "import 'package:flutter/widgets.dart';",
        "",
        "abstract final class ApIcons {",
    ]
    for code, name in cmap.items():
        lines.append(
            f"  static const IconData {name} = "
            f"IconData(0x{code:x}, fontFamily: '{FAMILY}');"
        )
    lines += ["}", ""]
    DART.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} icons -> {FONT.relative_to(ROOT)}, {DART.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
